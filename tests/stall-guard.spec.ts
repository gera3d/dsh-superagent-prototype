import { describe, expect, it, vi } from 'vitest'
import { Engine, MemoryRepositories, canRetry, type EngineOptions, type Ticket } from '../src/core/index.ts'
import { isStallGuardStuck, stallCandidate } from '../src/core/stall-guard.ts'
import { ExecutorConfigSchema } from '../src/policy.ts'

const start = '2026-11-05T20:00:00.000Z'
function fixture(signal = 'Fell back to available ladder model (example/model): unavailable.') {
  let clock = Date.parse(start), busy = false, paused = false
  const repo = new MemoryRepositories()
  const ticket: Ticket = { id: 't', title: 'Fix issue', decisionId: 'd', mandate: { strength: 'explicit', policyVersion: 'v', basis: { via: 'listed' }, actor: { source: 'github', id: 'owner' }, scope: 'fix' }, channels: [],
    createdAt: start, updatedAt: start, origin: { triggerId: 'issue', triggerIds: ['issue'] },
    assignments: [{ id: 'a', state: 'running', createdAt: start, startedAt: start, idleAt: start, report: { state: 'waiting', summary: 'Not started', at: start } }],
    inputs: [{ id: 'signal', kind: 'note', text: signal, at: start }], undelivered: [] }
  repo.tickets.save(ticket)
  repo.triggers.save({ id: 'issue', source: 'github', threads: [{ source: 'github', id: '143' }], actor: { source: 'github', id: 'owner' }, human: true, at: start, text: 'Original implementation task', url: 'https://github.com/example/repo/issues/143', meta: {} })
  const executor = { start: vi.fn(), stop: vi.fn(), deliver: vi.fn() }
  const options: EngineOptions = { repo, policy: () => ({ version: 'v', paused, evalTimeoutMs: 60000, gate: () => ({ admissible: false, reason: 'test' }), revalidate: () => true, admitsInferred: () => false }),
    scope: { scope: () => ({ listened: true, observed: false }) }, assessor: { request: vi.fn(), release: vi.fn() }, executor,
    outbox: { send: vi.fn(), status: () => undefined, withdraw: vi.fn() }, now: () => new Date(clock).toISOString(), workerBusy: () => busy }
  const engine = new Engine(options)
  const get = () => repo.tickets.get('t')!
  const mutate = (fn: (t: Ticket) => void) => { const t = get(); fn(t); repo.tickets.save(t) }
  const idle = () => { engine.inputsDelivered('t', 'a', get().undelivered); engine.turnEnded('t', 'a') }
  return { repo, engine, options, executor, get, mutate, idle, tick: (seconds: number) => { clock += seconds * 1000 }, busy: () => { busy = true }, pause: () => { paused = true } }
}

describe('stall guard', () => {
  it.each(['Fell back to available ladder model (example/model): offline.', 'Fell back to DeepSeek cheap flash model (example/model): offline.', 'Report the current ticket status with orchestrator_report. This is a status-only request: do not resume implementation or perform external actions.'])('detects %s and wakes exactly once across engine reload', signal => {
    const h = fixture(signal)
    expect(stallCandidate(h.get())).toBe(true)
    h.engine.evaluateDue()
    expect(h.get().inputs.at(-1)).toMatchObject({ kind: 'text', text: expect.stringContaining('The status request is over. Continue the original task') })
    expect(h.executor.deliver).toHaveBeenCalledTimes(1)
    h.idle(); new Engine(h.options).evaluateDue(); h.engine.evaluateDue()
    h.mutate(t => { t.inputs.push({ id: 'later-status', kind: 'text', at: start, text: 'This is a status-only request: do not resume implementation' }) })
    h.engine.evaluateDue()
    expect(h.executor.deliver).toHaveBeenCalledTimes(1)
  })
  it('detects the real status-only request generated by the engine', () => {
    const h = fixture('Unrelated note')
    expect(h.engine.requestStatus('t')).toBe(true)
    h.idle(); h.engine.evaluateDue()
    expect(h.get().inputs.at(-1)).toMatchObject({ kind: 'text', text: expect.stringContaining('The status request is over.') })
    expect(h.get().stallGuard?.assignmentId).toBe('a')
  })
  it('escalates only after the configured wait and never while busy', () => {
    const h = fixture(); h.engine.evaluateDue(); h.idle(); h.tick(179); h.engine.evaluateDue()
    expect(isStallGuardStuck(h.get())).toBe(false)
    h.tick(1); h.engine.evaluateDue()
    expect(isStallGuardStuck(h.get())).toBe(true)
    const other = fixture(); other.options.stallWaitSeconds = () => 10
    other.engine.evaluateDue(); other.idle(); other.tick(10); other.busy(); other.engine.evaluateDue()
    expect(isStallGuardStuck(other.get())).toBe(false)
  })
  it('starts the escalation clock at the wake, not an old progress report', () => {
    const h = fixture(); h.mutate(t => { t.assignments[0]!.report!.state = 'progress' })
    h.tick(600); h.engine.evaluateDue(); h.idle(); h.tick(1); h.engine.evaluateDue()
    expect(isStallGuardStuck(h.get())).toBe(false)
    h.tick(179); h.engine.evaluateDue(); expect(isStallGuardStuck(h.get())).toBe(true)
  })
  it('resets the escalation interval on progress even when followed by waiting', () => {
    const h = fixture(); h.engine.evaluateDue(); h.idle(); h.tick(170)
    h.engine.report('t', { state: 'progress', summary: 'Implemented change' })
    h.engine.report('t', { state: 'waiting', summary: 'Idle' }); h.tick(10); h.engine.evaluateDue()
    expect(isStallGuardStuck(h.get())).toBe(false)
    h.tick(170); h.engine.evaluateDue(); expect(isStallGuardStuck(h.get())).toBe(true)
  })
  it.each(['ended', 'attention', 'ready', 'blocked', 'failed', 'pr', 'pending', 'undelivered', 'delivered', 'no signal'] as const)('does not wake %s tickets', condition => {
    const h = fixture()
    h.mutate(t => {
      if (condition === 'ended') t.ended = { by: 'human', at: start, outcome: 'stopped' }
      if (condition === 'attention') t.attention = { id: 'q', question: 'Need permission' }
      if (['ready', 'blocked', 'failed'].includes(condition)) t.assignments[0]!.report!.state = condition as 'ready' | 'blocked' | 'failed'
      if (condition === 'pr') t.follows = [{ thread: 'github:144', own: true }]
      if (condition === 'pending') t.assignments[0]!.state = 'pending'
      if (condition === 'undelivered') t.undelivered = ['signal']
      if (condition === 'delivered') t.assignments[0]!.deliveredAt = '2026-11-05T20:01:00.000Z'
      if (condition === 'no signal') t.inputs = []
    })
    h.engine.evaluateDue(); expect(h.executor.deliver).not.toHaveBeenCalled()
    expect(stallCandidate(h.get())).toBe(false)
  })
  it('does not recover while processing is paused', () => {
    const h = fixture(); h.pause(); h.engine.evaluateDue(); expect(h.executor.deliver).not.toHaveBeenCalled()
  })
  it('allows idle fallback retry and redelivers the original task, not the status input', () => {
    const h = fixture(); expect(canRetry(h.get())).toBe(true)
    h.engine.retryTicket('t')
    expect(h.executor.start).toHaveBeenCalledOnce()
    expect(h.get().inputs.at(-1)).toMatchObject({ kind: 'text', text: expect.stringContaining('Original implementation task') })
    expect(h.get().assignments).toHaveLength(2)
    expect(canRetry(h.get())).toBe(false)
  })
  it('refuses retry when the native worker is running', () => {
    const h = fixture(); h.busy(); expect(() => h.engine.retryTicket('t')).toThrow()
  })
  it('defaults the wait to three minutes and validates settings', () => {
    expect(ExecutorConfigSchema.parse({}).stallWaitSeconds).toBe(180)
    expect(ExecutorConfigSchema.parse({ stallWaitSeconds: 10 }).stallWaitSeconds).toBe(10)
    expect(() => ExecutorConfigSchema.parse({ stallWaitSeconds: 0 })).toThrow()
  })
})
