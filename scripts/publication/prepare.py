#!/usr/bin/env python3
"""Prepare a candidate release manifest read-only against GitHub; never apply/restart.
This does not fabricate local check/review evidence or install the manifest in runtime state.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def asset(path):
    return {'path': str(path), 'sha256': sha(path)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ['repository', 'pr', 'patch', 'target', 'release-dir', 'gh', 'pnpm', 'restart-script', 'verify-url', 'verify-contains']:
        parser.add_argument('--' + name, required=True)
    parser.add_argument('--local-evidence', help='Existing independent review/check attestation; never generated by preparation')
    parser.add_argument('--baseline-report', help='Reviewed immutable complete Vitest JSON report; not a failure count')
    parser.add_argument('--baseline-head', help='Actual 40-hex commit tested by the immutable baseline')
    parser.add_argument('--baseline-root', help='Original absolute checkout root in baseline JSON; defaults target')
    parser.add_argument('--targeted-test', action='append', default=[], help='Finite tracked test path run instead of the full suite at build (repeatable); exclusive with a baseline')
    parser.add_argument('--timeout-ms', type=int, default=600000, help='Per-phase deadline in milliseconds, 1000..900000 (default 600000; includes build plus full tests)')
    args = parser.parse_args()
    if not 1000 <= args.timeout_ms <= 900000:
        raise RuntimeError('Publication timeout must be between 1000 and 900000 milliseconds')
    if bool(args.baseline_report) != bool(args.baseline_head) or (args.baseline_head and not re.fullmatch('[a-f0-9]{40}', args.baseline_head)):
        raise RuntimeError('Baseline report and exact baseline head must be provided together')
    if args.targeted_test and (args.baseline_report or not 1 <= len(args.targeted_test) <= 50 or len(set(args.targeted_test)) != len(args.targeted_test)
                               or not all(re.fullmatch(r'tests/[A-Za-z0-9_.-]+(?:/[A-Za-z0-9_.-]+)*\.spec\.tsx?', t) and '..' not in t for t in args.targeted_test)):
        raise RuntimeError('Invalid targeted test list')
    if not re.fullmatch(r'[\w.-]+/[\w.-]+', args.repository) or not args.pr.isdecimal() or int(args.pr) < 1:
        raise RuntimeError('Invalid repository/PR')
    source = Path(__file__).resolve().parent
    patch = Path(args.patch).resolve(strict=True)
    target = Path(args.target).resolve(strict=True)
    gh = Path(args.gh).resolve(strict=True)
    pnpm = Path(args.pnpm).resolve(strict=True)
    restart = Path(args.restart_script).resolve(strict=True)
    if not target.is_dir() or not all(p.is_file() for p in [patch, gh, pnpm, restart]):
        raise RuntimeError('Invalid configured file/directory')
    metadata = json.loads(subprocess.check_output([str(gh), 'pr', 'view', args.pr, '--repo', args.repository, '--json', 'headRefOid,state'], text=True, timeout=90))
    head = metadata['headRefOid']
    if not re.fullmatch('[a-f0-9]{40}', head) or metadata['state'] not in ['OPEN', 'MERGED']:
        raise RuntimeError('Candidate must have an actual open/merged GitHub head')
    if head not in args.verify_contains and sha(patch) not in args.verify_contains:
        raise RuntimeError('Verification marker must contain exact head or patch fingerprint')
    release = Path(args.release_dir).resolve()
    # Never overwrite an earlier release, its operator manifest or rollback ledger.
    release.mkdir(parents=True, exist_ok=False)
    pins = {'repository': args.repository, 'prNumber': int(args.pr), 'headSha': head, 'patchSha256': sha(patch)}
    shutil.copy2(patch, release / 'release.patch')
    shutil.copy2(source / 'runner.py', release / 'publication-runner.py')
    plan = {'version': 1, 'repository': args.repository, 'headSha': head, 'patchSha256': pins['patchSha256'], 'target': str(target), 'pnpmPath': str(pnpm),
            'restartScript': asset(restart), 'verifyUrl': args.verify_url, 'verifyContains': args.verify_contains}
    if args.targeted_test:
        plan['targetedTests'] = list(args.targeted_test)
    baseline_dependencies = []
    if args.baseline_report:
        baseline_path = Path(args.baseline_report).resolve(strict=True)
        baseline_root = str(Path(args.baseline_root or target).resolve())
        # Validate complete raw baseline report before emitting an executable manifest.
        import runpy
        runpy.run_path(str(source / 'baseline.py'))['assertions'](json.loads(baseline_path.read_text()), baseline_root)
        shutil.copy2(baseline_path, release / 'baseline-report.json')
        shutil.copy2(source / 'baseline.py', release / 'publication-baseline.py')
        shutil.copy2(source / 'errors-reporter.cjs', release / 'publication-errors-reporter.cjs')
        plan['baselineReport'] = dict(asset(release / 'baseline-report.json'), baselineHead=args.baseline_head, root=baseline_root)
        baseline_dependencies = [asset(release / name) for name in ['baseline-report.json', 'publication-baseline.py', 'publication-errors-reporter.cjs']]
    plan_path = release / 'publication-plan.json'
    plan_path.write_text(json.dumps(plan, indent=2) + '\n')
    dependencies = [asset(release / 'publication-runner.py'), asset(plan_path), asset(pnpm), asset(restart)] + baseline_dependencies
    scripts = {}
    for phase in ['apply', 'build', 'restart', 'verify', 'rollback']:
        destination = release / (phase + '.sh')
        shutil.copy2(source / (phase + '.sh'), destination)
        scripts[phase] = dict(asset(destination), dependencies=dependencies)
    manifest = {'version': 1, 'pins': pins, 'ghPath': str(gh), 'cwd': str(release), 'patch': asset(release / 'release.patch'), 'scripts': scripts, 'timeoutMs': args.timeout_ms}
    if args.local_evidence:
        evidence = Path(args.local_evidence).resolve(strict=True)
        value = json.loads(evidence.read_text())
        if value.get('pins') != pins:
            raise RuntimeError('Local evidence is not bound to actual GitHub head and selected patch')
        if args.baseline_report and not any(plan['baselineReport']['sha256'] in text and args.baseline_head in text for text in value.get('limitations', [])):
            raise RuntimeError('Independent local evidence must disclose exact baseline hash and commit limitation')
        # Reports remain independently produced immutable assets; the adapter validates freshness and hashes.
        shutil.copy2(evidence, release / 'local-evidence.json')
        manifest['localEvidence'] = asset(release / 'local-evidence.json')
    manifest_path = release / 'publication-runner.json'
    manifest_path.write_text(json.dumps(manifest, indent=2) + '\n')
    print(json.dumps({'manifest': str(manifest_path), 'pins': pins, 'installed': False,
                      'limitations': ['Not applied or restarted', 'Operator must validate target/patch binding and independent evidence', 'Single-target conservative patch support', 'GUI acceptance remains separate']}, indent=2))


if __name__ == '__main__':
    try:
        main()
    except Exception as error:
        print('STOP: ' + str(error), file=sys.stderr)
        sys.exit(1)
